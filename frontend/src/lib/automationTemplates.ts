import type { BlockType, FlowEdge, FlowGraph, FlowNode } from "@/lib/automations";

export type FlowTemplate = { id: string; name: string; description: string; graph: FlowGraph };
const node = (id: string, type: BlockType, title: string, x: number, y: number, config: Record<string, string> = {}): FlowNode => ({ id, type, title, x, y, config });
const edge = (source: string, target: string, sourceHandle: FlowEdge["sourceHandle"] = "default"): FlowEdge => ({ id: `${source}-${sourceHandle}-${target}`, source, target, sourceHandle });
const graph = (nodes: FlowNode[], edges: FlowEdge[]): FlowGraph => ({ schemaVersion: 1, nodes, edges });

